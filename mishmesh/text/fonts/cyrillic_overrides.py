# Cyrillic atlas data for Body.c, Subtitle.c, and Caption.c.
# Rows use # for a lit OLED pixel and . for an unlit pixel; the first row is the
# top of the glyph cell (offset_y 0), so accented capitals have room for a mark
# above the cap and descenders reach the two rows below the baseline.
#
# The Russian letters are hand-edited. The rest are composed from shapes already
# in the font - Latin twins (S I J), mirrored E-forms, soft-sign ligatures and
# diacritics lifted off the accented Latin - so weight and baseline match by
# construction. Regenerate with build_cyrillic.py.


