#!/usr/bin/env python3
"""Merge typographic punctuation (U+2013..U+2026) into mcufont C sources.

Phones with smart punctuation send curly quotes, dashes and the ellipsis
character, none of which the source fonts carry, so they rendered as the
missing-glyph block. Rows use the same notation and cell heights as
cyrillic_overrides.py. Quotes copy the font's own ' " and , because Nokia's
U+2019 is drawn identical to the straight apostrophe. Caption's bullet and
ellipsis are taken from tom-thumb.bdf, which has them.
"""

import sys

from build_cyrillic import ROLE_CONFIG, merge

# One dense range; the 10 empty slots cost less than extra range entries.
RANGES = [(0x2013, 0x2026)]


def glyph(advance, rows):
    return advance, rows.split("/")


GLYPHS = {
    "Body": {
        "\u2013": glyph(6, "...../...../...../...../#####/...../...../...../...../....."),
        "\u2014": glyph(9, "......../......../......../......../########/......../......../......../......../........"),
        "\u2018": glyph(2, "./#/#/././././././."),
        "\u2019": glyph(2, "./#/#/././././././."),
        "\u201a": glyph(3, "../../../../../../.#/##/#./.."),
        "\u201c": glyph(4, ".../#.#/#.#/.../.../.../.../.../.../..."),
        "\u201d": glyph(4, ".../#.#/#.#/.../.../.../.../.../.../..."),
        "\u201e": glyph(4, ".../.../.../.../.../.../.../#.#/#.#/..."),
        "\u2022": glyph(4, ".../.../.../###/###/###/.../.../.../..."),
        "\u2026": glyph(9, "......../......../......../......../......../......../##.##.##/##.##.##/......../........"),
    },
    "Subtitle": {
        "\u2013": glyph(10, "/".join(["........"] * 6 + ["########"] + ["........"] * 8)),
        "\u2014": glyph(14, "/".join(["............"] * 6 + ["############"] + ["............"] * 8)),
        "\u2018": glyph(3, "/".join(["."] + ["#"] * 3 + ["."] * 11)),
        "\u2019": glyph(3, "/".join(["."] + ["#"] * 3 + ["."] * 11)),
        "\u201a": glyph(5, "/".join(["..."] * 9 + ["..#", "..#", "###", "#..", "#..", "..."])),
        "\u201c": glyph(6, "/".join(["...."] + ["#..#"] * 3 + ["...."] * 11)),
        "\u201d": glyph(6, "/".join(["...."] + ["#..#"] * 3 + ["...."] * 11)),
        "\u201e": glyph(6, "/".join(["...."] * 11 + ["#..#"] * 3 + ["...."])),
        "\u2022": glyph(6, "/".join(["...."] * 5 + [".##.", "####", "####", ".##."] + ["...."] * 6)),
        "\u2026": glyph(13, "/".join(["..........."] * 9 + ["###.###.###"] * 3 + ["..........."] * 3)),
    },
    "Caption": {
        "\u2013": glyph(4, ".../.../###/.../.../..."),
        "\u2014": glyph(4, "..../..../####/..../..../...."),
        "\u2018": glyph(4, ".#/.#/../../../.."),
        "\u2019": glyph(4, ".#/.#/../../../.."),
        "\u201a": glyph(4, "../../../.#/#./.."),
        "\u201c": glyph(4, "#.#/#.#/.../.../.../..."),
        "\u201d": glyph(4, "#.#/#.#/.../.../.../..."),
        "\u201e": glyph(4, ".../.../.../#.#/#.#/..."),
        "\u2022": glyph(4, "../../.#/../../.."),
        "\u2026": glyph(4, ".../.../.../.../#.#/..."),
    },
}


def overrides():
    out = {}
    for role, glyphs in GLYPHS.items():
        empty = glyph(0, "/".join([""] * ROLE_CONFIG[role]["height"]))
        out[role] = {chr(cp): glyphs.get(chr(cp), empty)
                     for lo, hi in RANGES for cp in range(lo, hi + 1)}
    return out


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: build_punct.py <Body.c|Subtitle.c|Caption.c>")
    merge(sys.argv[1], RANGES, overrides(), "punct",
          "Typographic punctuation. Generated by build_punct.py.", "punct")
